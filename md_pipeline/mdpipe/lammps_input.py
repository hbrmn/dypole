"""Step 3 -- write the LAMMPS input script for one run.

The thermal history (melt, quench, relax, production) is a list of "stages"
in the master input. Each stage type below turns into a small block of
LAMMPS commands. To add a new kind of stage, write one more function and
register it in STAGES.
"""

import itertools
import os


def _steps(time_ps, dt_fs):
    return max(1, int(round(time_ps * 1000.0 / dt_fs)))


def header(meta, cfg):
    pot = cfg['_potential']
    sim = cfg['simulation']
    els = meta['elements']
    lines = [
        f"# LAMMPS input generated by mdpipe for {meta['tag']}",
        f"# composition (mol%): {meta['real_mol_percent']}",
        "# atom types: " + ' '.join(f'{i + 1}={e}' for i, e in enumerate(els)),
        'units           metal',
        'atom_style      charge',
        'boundary        p p p',
        'read_data       structure.data',
        '',
        '# ---- force field: ' + pot['name'],
        'pair_style      ' + pot['pair_style'].format(sr_cut=pot['short_range_cutoff'],
                                                      coul_cut=pot['coulomb_cutoff']),
    ]
    lines += pot.get('global_coeffs', [])
    for (i, a), (j, b) in itertools.combinations_with_replacement(enumerate(els, 1), 2):
        params = pot['pairs'].get(f'{a}-{b}') or pot['pairs'].get(f'{b}-{a}')
        if params is not None:
            lines.append(f'pair_coeff      {i} {j} ' + pot['pair_coeff'].format(*params)
                         + f'   # {a}-{b}')
    lines += [
        'kspace_style    ' + pot['kspace_style'],
        '',
        'neighbor        2.0 bin',
        'neigh_modify    every 1 delay 0 check yes',
        f"timestep        {sim['timestep_fs'] / 1000.0}",
        'thermo_style    custom step time temp press pe etotal vol density',
        f"thermo          {sim['thermo_every']}",
        'thermo_modify   flush yes',
        '',
    ]
    return lines


def st_minimize(s, meta, cfg, dt):
    return ['minimize        1.0e-6 1.0e-8 2000 20000', 'reset_timestep  0']


def st_relax(s, meta, cfg, dt):
    """Remove bad contacts of the random start: limited displacements + Langevin."""
    T = s.get('T', 300)
    return [
        f"fix             lim all nve/limit {s.get('max_disp', 0.1)}",
        f"fix             lang all langevin {T} {T} 0.1 {meta['seed']}",
        f"run             {_steps(s['time_ps'], dt)}",
        'unfix           lim', 'unfix           lang',
    ]


def _thermostat(s, T1, T2, dt):
    ens = s.get('ensemble', 'nvt')
    tdamp = s.get('Tdamp_ps', 100 * dt / 1000.0)
    if ens == 'nvt':
        return f'fix             integ all nvt temp {T1} {T2} {tdamp}'
    if ens == 'npt':
        P = s.get('P_bar', 0.0)
        pdamp = s.get('Pdamp_ps', 1000 * dt / 1000.0)
        return f'fix             integ all npt temp {T1} {T2} {tdamp} iso {P} {P} {pdamp}'
    if ens == 'nve':
        return 'fix             integ all nve'
    raise ValueError(f'Unknown ensemble {ens}')


def st_equilibrate(s, meta, cfg, dt):
    return [_thermostat(s, s['T'], s['T'], dt),
            f"run             {_steps(s['time_ps'], dt)}",
            'unfix           integ']


def st_ramp(s, meta, cfg, dt):
    """Linear heating or quench. Give either rate_K_per_ps or time_ps."""
    T1, T2 = s['T_start'], s['T_end']
    time_ps = s.get('time_ps') or abs(T1 - T2) / s['rate_K_per_ps']
    return [f'# {T1} K -> {T2} K in {time_ps:g} ps',
            _thermostat(s, T1, T2, dt),
            f'run             {_steps(time_ps, dt)}',
            'unfix           integ']


def st_production(s, meta, cfg, dt):
    """Run that is analysed: writes a trajectory with unwrapped coordinates and
    LAMMPS' own RDF (as a cross-check of the Python analysis)."""
    ana = cfg['analysis']
    nevery = _steps(s.get('dump_every_ps', 1.0), dt)
    n = len(meta['elements'])
    pairs = ' '.join(f'{i} {j}' for i, j in itertools.combinations_with_replacement(range(1, n + 1), 2))
    nbins = int(round(ana['r_max'] / ana['dr']))
    nsteps = _steps(s['time_ps'], dt)
    return [
        'reset_timestep  0',
        _thermostat(s, s['T'], s['T'], dt),
        'dump            traj all custom {} traj.lammpstrj id type xu yu zu'.format(nevery),
        'dump_modify     traj sort id',
        f"compute         rdf all rdf {nbins} {pairs} cutoff {ana['r_max']}",
        f'fix             rdf all ave/time {nevery} {nsteps // nevery} {nsteps} '
        'c_rdf[*] file rdf_lammps.dat mode vector',
        f'fix             thermo_avg all ave/time {nevery} 1 {nevery} '
        'c_thermo_temp c_thermo_press c_thermo_pe v_rho file thermo_production.dat',
        f'run             {nsteps}',
        'undump          traj', 'unfix           rdf', 'unfix           thermo_avg',
        'unfix           integ',
    ]


STAGES = {
    'minimize': st_minimize,
    'relax': st_relax,
    'equilibrate': st_equilibrate,
    'ramp': st_ramp,
    'production': st_production,
}


def write_input(run_dir, meta, cfg):
    sim = cfg['simulation']
    dt = sim['timestep_fs']
    lines = header(meta, cfg)
    lines += ['variable        rho equal density', '']
    T0 = sim.get('initial_T', 300)
    lines.append(f"velocity        all create {T0} {meta['seed']} dist gaussian mom yes rot yes")
    for k, s in enumerate(sim['stages']):
        kind = s['type']
        label = s.get('name', f'{k + 1}_{kind}')
        lines += ['', f'# ===== stage {label} =====', f'print "STAGE {label}"']
        lines += STAGES[kind](s, meta, cfg, dt)
        lines.append(f'write_restart   stage_{label}.restart')
    lines += ['', 'write_data      final.data', 'print "PIPELINE_FINISHED"']
    path = os.path.join(run_dir, 'in.lammps')
    with open(path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    return path
